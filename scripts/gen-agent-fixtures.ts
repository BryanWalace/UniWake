/**
 * Regenerates `packages/shared/fixtures/agent/signature.json` (M16-T01, ADR-044): an answer body
 * signed by a throwaway RSA-3072 key, so Vitest (Node) and Pester (Windows PowerShell 5.1) prove
 * they agree on the signed bytes and the key id. The private key is never written anywhere.
 * Run with `node scripts/gen-agent-fixtures.ts`.
 */
import { createHash, generateKeyPairSync, sign } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const { publicKey, privateKey } = generateKeyPairSync('rsa', { modulusLength: 3072 });
const jwk = publicKey.export({ format: 'jwk' }) as { n: string; e: string };

/** RFC 7638 JWK thumbprint: SHA-256 over the required members in lexicographic order. */
const keyId = createHash('sha256')
  .update(`{"e":"${jwk.e}","kty":"RSA","n":"${jwk.n}"}`)
  .digest('base64url');

const nonce = 'q5KX2nX0v4m8Zk1d0b7S9w';
// Non-ASCII text on purpose: the agent must verify the exact UTF-8 bytes, not a decoded string.
const body = JSON.stringify({
  serverTime: 1_791_766_800_000,
  orders: [],
  agenda: { version: 'v1', window: { from: 1_791_766_800_000, to: 1_792_976_400_000 }, items: [] },
  message: 'Este computador será desligado às 22:40 pela equipe de TI.',
});
const bodyBytes = Buffer.from(body, 'utf8');
const prefix = Buffer.from(`uniwake-agent-v1\n${nonce}\n`, 'utf8');
const signature = sign('sha256', Buffer.concat([prefix, bodyBytes]), privateKey).toString('base64');

const tampered = Buffer.from(body.replace('22:40', '22:41'), 'utf8');

const dir = join(import.meta.dirname, '..', 'packages', 'shared', 'fixtures', 'agent');
mkdirSync(dir, { recursive: true });
writeFileSync(
  join(dir, 'signature.json'),
  JSON.stringify(
    {
      comment: 'Generated by scripts/gen-agent-fixtures.ts; throwaway key, private part discarded.',
      key: { kty: 'RSA', n: jwk.n, e: jwk.e },
      keyId,
      nonce,
      bodyBase64: bodyBytes.toString('base64'),
      signature,
      tamperedBodyBase64: tampered.toString('base64'),
    },
    null,
    2,
  ) + '\n',
);
console.log(`fixture written, key id ${keyId}`);
